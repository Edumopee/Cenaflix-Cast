    // Método para configurar o acesso do usuário
    private void configurarAcesso(String tipoUsuario) {
        if (tipoUsuario != null && (tipoUsuario.equalsIgnoreCase("Administrador") || tipoUsuario.equalsIgnoreCase("Operador"))) {
            btnCadastrar.setVisible(true);
            btnCadastrar.setEnabled(true);
        } else {
            btnCadastrar.setVisible(false);
            btnCadastrar.setEnabled(false);
        }
    }
    
    // Método para carregar a tabela
    private void carregarTabela() {
        DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
        model.setRowCount(0);
        
        List<Cadastro> podcasts = dao.listarTodos();

        for (Cadastro podcast : podcasts) {
            model.addRow(new Object[]{
                podcast.getId(),
                podcast.getProdutor(),
                podcast.getNomeEpisodio(),
                podcast.getNumeroEpisodio(),
                podcast.getDuracao(),
                podcast.getUrl()
            });
        }
    }
    
    

