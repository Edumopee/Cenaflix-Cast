    // Método para filtrar a tabela com base no campo de pesquisa
    private void filtrarTabela() {
        DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
        model.setRowCount(0);
        
        String termo = txtPesquisa.getText();
        
        List<Cadastro> podcasts;
        if (termo.isEmpty()) {
            podcasts = dao.listarTodos();
        } else {
            podcasts = dao.listarPorProdutor(termo);
        }

        for (Cadastro podcast : podcasts) {
            model.addRow(new Object[]{
                podcast.getId(),
                podcast.getProdutor(),
                podcast.getNomeEpisodio(),
                podcast.getNumeroEpisodio(),
                podcast.getDuracao(),
                podcast.getUrl()
            });
        }
    }
    
    // Métodos da interface DocumentListener
    @Override
    public void insertUpdate(DocumentEvent e) {
        filtrarTabela();
    }

